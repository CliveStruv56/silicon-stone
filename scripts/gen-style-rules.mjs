#!/usr/bin/env node
/**
 * gen-style-rules.mjs — codegen the canonical style rules into a bundled TS
 * module the web app imports at build time.
 *
 * WHY: the article-generation prompt must reliably carry the house style and
 * AI-tells rules. Runtime fs.readFile of repo .md files is unreliable on Vercel
 * (see getContentFocus, whose target file silently resolves to ""). A real
 * module import is traced into the server bundle and always reaches the prompt —
 * the same channel that makes voice-dna.json reliable.
 *
 * SOURCE OF TRUTH: the Ideaverse vault Style/ dir, synced into
 * .agent/rules/style/ by sync-style.sh. This script reads those synced copies;
 * it never edits them. Re-run via `npm run gen:style` (also invoked by
 * sync-style.sh and the npm prebuild hook).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STYLE_DIR = join(ROOT, '.agent/rules/style');
const OUT = join(ROOT, 'src/lib/style-rules.generated.ts');

/** Strip a leading YAML frontmatter block — it is repo metadata, not prompt content. */
function stripFrontmatter(text) {
    if (!text.startsWith('---')) return text;
    const end = text.indexOf('\n---', 3);
    if (end === -1) return text;
    const after = text.indexOf('\n', end + 1);
    return after === -1 ? '' : text.slice(after + 1).trimStart();
}

/** Read a synced rule file; fail loudly so a missing rule never ships as "". */
function readRule(name) {
    const path = join(STYLE_DIR, name);
    try {
        const text = stripFrontmatter(readFileSync(path, 'utf-8').trim());
        if (!text) throw new Error('file is empty');
        return text;
    } catch (err) {
        console.error(
            `[gen-style-rules] Could not read ${path}: ${err.message}\n` +
            `Run the vault's sync-style.sh first so the canonical rules are synced.`,
        );
        process.exit(1);
    }
}

const houseStyle = readRule('house-style.md');
const aiTells = readRule('ai-tells.md');

const banner =
    `// AUTO-GENERATED by scripts/gen-style-rules.mjs — DO NOT EDIT BY HAND.\n` +
    `// Source of truth: Ideaverse vault Style/ -> .agent/rules/style/*.md (synced via sync-style.sh).\n` +
    `// Regenerate with: npm run gen:style\n\n`;

const body =
    `export const HOUSE_STYLE_RULES = ${JSON.stringify(houseStyle)};\n\n` +
    `export const AI_TELLS_RULES = ${JSON.stringify(aiTells)};\n`;

writeFileSync(OUT, banner + body, 'utf-8');
console.log(`[gen-style-rules] Wrote ${OUT} (house-style ${houseStyle.length} chars, ai-tells ${aiTells.length} chars)`);
