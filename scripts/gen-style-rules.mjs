#!/usr/bin/env node
/**
 * gen-style-rules.mjs — codegen the prompt inputs that must be bundled into TS
 * modules the web app imports at build time.
 *
 * WHY: the article-generation prompt must reliably carry the house style, the
 * AI-tells rules and the editorial content focus. Runtime fs.readFile of repo
 * .md files is unreliable on Vercel: the path is assembled from process.cwd()
 * at runtime, so Next's file tracing cannot resolve it and never includes the
 * file in the function bundle — the read then fails and the value silently
 * becomes "". A real module import is traced and always reaches the prompt, the
 * same channel that makes voice-dna.json reliable.
 *
 * getContentFocus was the last holdout and this note used to cite it as the
 * example of the failure. It was worse than an example: knowledge/company/
 * content-focus.md did not exist at all until 21 August 2026, so the
 * "Current Content Focus Areas" section had been omitted from every draft
 * prompt on every path, and the miss logged once per process where nobody read
 * it. Adding the file fixed local runs; only bundling it fixes production.
 *
 * SOURCE OF TRUTH: .agent/rules/style/*.md in this repo — edit those directly.
 * (They were previously rsynced in from an Obsidian vault by a sync-style.sh
 * that lived in the vault root; that vault is retired.)
 *
 * This script also mirrors the two canonical rule files into the voice-edit
 * skill's references/ dir, which the vault script used to do. That kept the
 * `/voice-edit` skill from drifting out of step with the prompt rules, so it
 * happens here now. Re-run via `npm run gen:style` (also on npm prebuild).
 */
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STYLE_DIR = join(ROOT, '.agent/rules/style');
const OUT = join(ROOT, 'src/lib/style-rules.generated.ts');

/* The editorial steer. Optional by design — a repo without one still builds —
 * but its absence is announced here, at build time, rather than discovered
 * never. See getContentFocus in src/lib/api.ts. */
const CONTENT_FOCUS_SRC = join(ROOT, 'knowledge/company/content-focus.md');
const CONTENT_FOCUS_OUT = join(ROOT, 'src/lib/content-focus.generated.ts');

/* The voice-edit skill reads its own copies of the rules. Keep them in step with
 * the canonical files — a stale reference here means the manual /voice-edit pass
 * enforces different rules from the automated one. */
const SKILL_REFS = join(ROOT, '.agent/skills/voice-edit/references');
const SKILL_REF_FILES = [
    ['house-style.md', 'HOUSE-STYLE.md'],
    ['ai-tells.md', 'AI-TELLS.md'],
];

/** Strip a leading YAML frontmatter block — it is repo metadata, not prompt content. */
function stripFrontmatter(text) {
    if (!text.startsWith('---')) return text;
    const end = text.indexOf('\n---', 3);
    if (end === -1) return text;
    const after = text.indexOf('\n', end + 1);
    return after === -1 ? '' : text.slice(after + 1).trimStart();
}

/** Read a synced rule file; fail loudly so a missing rule never ships as "". */
function readRule(name) {
    const path = join(STYLE_DIR, name);
    try {
        const text = stripFrontmatter(readFileSync(path, 'utf-8').trim());
        if (!text) throw new Error('file is empty');
        return text;
    } catch (err) {
        console.error(
            `[gen-style-rules] Could not read ${path}: ${err.message}\n` +
            `That file is canonical and must exist — restore it from git history.`,
        );
        process.exit(1);
    }
}

const houseStyle = readRule('house-style.md');
const aiTells = readRule('ai-tells.md');

const banner =
    `// AUTO-GENERATED by scripts/gen-style-rules.mjs — DO NOT EDIT BY HAND.\n` +
    `// Source of truth: .agent/rules/style/*.md — edit those, then regenerate.\n` +
    `// Regenerate with: npm run gen:style\n\n`;

const body =
    `export const HOUSE_STYLE_RULES = ${JSON.stringify(houseStyle)};\n\n` +
    `export const AI_TELLS_RULES = ${JSON.stringify(aiTells)};\n`;

writeFileSync(OUT, banner + body, 'utf-8');
console.log(`[gen-style-rules] Wrote ${OUT} (house-style ${houseStyle.length} chars, ai-tells ${aiTells.length} chars)`);

/* Optional, unlike the style rules: absent means "omit the section", which is
 * a legitimate state. Loud at build time, never silent at runtime. */
let contentFocus = '';
try {
    contentFocus = stripFrontmatter(readFileSync(CONTENT_FOCUS_SRC, 'utf-8').trim());
} catch {
    console.warn(
        `[gen-style-rules] No content-focus file at ${CONTENT_FOCUS_SRC} — the ` +
        `"Current Content Focus Areas" section will be omitted from draft prompts. ` +
        `Create it to steer topic selection.`,
    );
}

writeFileSync(
    CONTENT_FOCUS_OUT,
    `// AUTO-GENERATED by scripts/gen-style-rules.mjs — DO NOT EDIT BY HAND.\n` +
    `// Source of truth: knowledge/company/content-focus.md — edit that, then regenerate.\n` +
    `// Regenerate with: npm run gen:style\n\n` +
    `export const CONTENT_FOCUS = ${JSON.stringify(contentFocus)};\n`,
    'utf-8',
);
console.log(
    contentFocus
        ? `[gen-style-rules] Wrote ${CONTENT_FOCUS_OUT} (content-focus ${contentFocus.length} chars)`
        : `[gen-style-rules] Wrote ${CONTENT_FOCUS_OUT} (content-focus EMPTY)`,
);

for (const [src, dest] of SKILL_REF_FILES) {
    try {
        copyFileSync(join(STYLE_DIR, src), join(SKILL_REFS, dest));
        console.log(`[gen-style-rules] Synced ${src} -> voice-edit/references/${dest}`);
    } catch (err) {
        console.error(`[gen-style-rules] Could not sync ${src} to ${SKILL_REFS}: ${err.message}`);
        process.exit(1);
    }
}
